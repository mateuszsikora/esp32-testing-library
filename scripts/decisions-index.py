#!/usr/bin/env python3
"""Generates docs/decisions/README.md from the `##` headings of the decision files.

    python3 scripts/decisions-index.py           rewrite the index
    python3 scripts/decisions-index.py --check   exit 1 if it is stale (make docs-check runs this)

Each `##` heading of docs/decisions/<domain>.md is one decision; the first line after it is
`Status: decided|postponed|superseded (...)`. The index lists every decision with its file, its
anchor and its status, so an agent can find out cheaply whether something was already settled.
Generated, because a hand-kept index goes stale, and a stale index answers "no such decision" for
one that exists.

`--check` also fails on a decision file that DOMAINS does not list, and on a domain whose file is
missing: a file the index silently skipped would be the same stale answer. Standard library only,
so it runs on any Python 3 without the repository's virtual environment.
"""

from __future__ import annotations

import re
import subprocess
import sys
from collections.abc import Iterator
from pathlib import Path

# Every decision file, in the order of the index, with its section title there.
DOMAINS = {
    "ci": "CI and runners",
    "docs": "Documentation and the documentation check",
    "firmware": "Validation firmware, ESP-IDF and the ROM ELF",
    "harness": "The esp32tl package and its pytest plugin",
    "runner": "The runner crate and esp32sim",
}

DECISIONS = Path("docs/decisions")
INDEX = DECISIONS / "README.md"
STATUS = re.compile(r"^Status: (decided|postponed|superseded)\b(.*)$")

HEADER = """\
# Decisions

Generated by `scripts/decisions-index.py` from the `##` headings of the files below: do not edit
it by hand, run the script. Each decision says what was chosen and what was rejected or postponed,
and why. Read this list before deciding something again; [the documentation
guide](../guides/documentation.md#decisions-docsdecisionsdomainmd) says how to add one.
"""


def headings(text: str) -> Iterator[tuple[int, str, int]]:
    """(level, text, line index) of every ATX heading outside fenced code blocks."""
    fence: str | None = None
    for number, line in enumerate(text.splitlines()):
        stripped = line.lstrip()
        marker = re.match(r"(`{3,}|~{3,})", stripped)
        if marker:
            if fence is None:
                fence = marker[1][0] * len(marker[1])
            elif stripped.startswith(fence):
                fence = None
            continue
        if fence is not None:
            continue
        heading = re.match(r"^(#{1,6})[ \t]+(.*?)(?:[ \t]+#+)?[ \t]*$", line)
        if heading:
            yield len(heading[1]), heading[2], number


def github_slug(text: str) -> str:
    """The anchor GitHub gives a heading: link text kept and markup dropped, lowercased,
    everything but letters, digits, `_`, `-` and spaces removed, spaces turned into `-`."""
    # In a code span, `<domain>` is text, not a tag: GitHub keeps "domain".
    text = re.sub(r"`([^`]*)`", lambda span: re.sub(r"[<>]", "", span[1]), text)
    text = re.sub(r"!?\[([^\]]*)\]\([^)]*\)", r"\1", text)
    text = re.sub(r"<[^>]+>", "", text)
    text = re.sub(r"[^\w\- ]", "", text.lower())
    return text.replace(" ", "-")


def anchors(text: str) -> set[str]:
    """Every anchor a link into this Markdown can use: the headings' slugs, numbered the way
    GitHub numbers repeated ones (`x`, `x-1`, `x-2`), and explicit `id`/`name` attributes."""
    seen: dict[str, int] = {}
    found: set[str] = set()
    for _, heading, _ in headings(text):
        slug = github_slug(heading)
        count = seen.get(slug, 0)
        found.add(slug if count == 0 else f"{slug}-{count}")
        seen[slug] = count + 1
    found.update(re.findall(r"""<a\s+(?:id|name)=["']([^"']+)["']""", text))
    return found


def decisions(root: Path, domain: str) -> tuple[list[tuple[str, str, str]], list[str]]:
    """The (title, anchor, status) of each decision in the domain's file, and its errors."""
    path = root / DECISIONS / f"{domain}.md"
    text = path.read_text(encoding="utf-8")
    lines = text.splitlines()
    found, errors = [], []
    slugs: dict[str, int] = {}
    for level, title, number in headings(text):
        slug = github_slug(title)
        count = slugs.get(slug, 0)
        slugs[slug] = count + 1
        if level != 2:
            continue
        anchor = slug if count == 0 else f"{slug}-{count}"
        following = next((line for line in lines[number + 1 :] if line.strip()), "")
        status = STATUS.match(following)
        if status is None:
            errors.append(
                f'{DECISIONS / domain}.md: "{title}" has no status: the first line after the'
                " heading must be `Status: decided|postponed|superseded (...)`"
            )
            continue
        found.append((title, anchor, (status[1] + status[2]).strip()))
    return found, errors


def generate(root: Path) -> tuple[str, list[str]]:
    """The index's text, and every error that keeps it from being right."""
    errors = []
    files = {p.stem for p in (root / DECISIONS).glob("*.md") if p.name != INDEX.name}
    for unknown in sorted(files - DOMAINS.keys()):
        errors.append(
            f"{DECISIONS / unknown}.md is not in DOMAINS in scripts/decisions-index.py:"
            " add it there, or the index leaves it out"
        )
    parts = [HEADER]
    for domain, title in DOMAINS.items():
        if domain not in files:
            errors.append(f"{DECISIONS / domain}.md is missing, but DOMAINS lists it")
            continue
        found, domain_errors = decisions(root, domain)
        errors += domain_errors
        parts.append(f"\n## {title}\n\n")
        if not found:
            parts.append(f"[`{domain}.md`]({domain}.md) holds no decision yet.\n")
            continue
        parts.append("| Decision | File | Status |\n|---|---|---|\n")
        for decision, anchor, status in found:
            cell = decision.replace("|", "\\|")
            parts.append(f"| [{cell}]({domain}.md#{anchor}) | `{domain}.md` | {status} |\n")
    return "".join(parts), errors


def check(root: Path) -> list[str]:
    """What is wrong with the index as committed; empty when it is up to date."""
    text, errors = generate(root)
    index = root / INDEX
    current = index.read_text(encoding="utf-8") if index.is_file() else None
    if current != text:
        errors.append(f"{INDEX} is stale: run python3 scripts/decisions-index.py")
    return errors


def main(argv: list[str]) -> int:
    if argv not in ([], ["--check"]):
        print("usage: decisions-index.py [--check]", file=sys.stderr)
        return 2
    root = Path(
        subprocess.run(
            ["git", "rev-parse", "--show-toplevel"], capture_output=True, text=True, check=True
        ).stdout.strip()
    )
    if argv == ["--check"]:
        errors = check(root)
    else:
        text, errors = generate(root)
        if not errors:
            (root / INDEX).write_text(text, encoding="utf-8")
            print(f"decisions-index: wrote {INDEX}")
    for error in errors:
        print(f"✗ {error}", file=sys.stderr)
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
